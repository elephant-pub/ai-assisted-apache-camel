-- Order Database schema V2 (pipeline 003-partner-orders-pick-lists, design §3 "Supporting change: Flyway V2").
-- Adds the registered Partners (UC-007) and the Pick List outbox (UC-004), and ties Partner receipts to their
-- Partner. Names and rules follow docs/entity_model.md, with the two changes of design review R1: deregistered_at on
-- partner, and a Partner receipt unique per partner, order number and content.
-- Flyway runs this script once at startup, before the Camel routes start. Never run it by hand.

CREATE TABLE partner (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_code        varchar(50)  NOT NULL UNIQUE,
  name                varchar(100) NOT NULL,
  api_key_name        varchar(100) NOT NULL UNIQUE,
  order_number_from   bigint       NOT NULL CHECK (order_number_from >= 0),
  order_number_to     bigint       NOT NULL CHECK (order_number_to >= 0),
  order_contact_email varchar(254) NOT NULL CHECK (order_contact_email ~ '^[^@\s]+@[^@\s]+[.][^@\s]+$'),
  registered_at       timestamptz  NOT NULL,
  -- Set when the Partner is no longer in the released Partner Configuration; the row stays, receipts refer to it
  deregistered_at     timestamptz,
  CONSTRAINT partner_order_number_range_ck CHECK (order_number_from <= order_number_to)
);

ALTER TABLE order_receipt
  ADD CONSTRAINT order_receipt_partner_fk FOREIGN KEY (partner_id) REFERENCES partner (id);

-- A Partner request is identified by its Partner, its Order Number and its content (C-5)
CREATE UNIQUE INDEX order_receipt_partner_content_uq
  ON order_receipt (partner_id, order_number, content_hash) WHERE channel = 'Partner';

-- At most one receipt per Order Number is Recorded or Sent to Warehouse
CREATE UNIQUE INDEX order_receipt_accepted_number_uq
  ON order_receipt (order_number) WHERE order_state IN ('Recorded', 'Sent to Warehouse');

CREATE TABLE pick_list (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_order_id bigint      NOT NULL UNIQUE REFERENCES customer_order (id),
  file_name         varchar(50) NOT NULL UNIQUE,
  total_weight_g    integer     NOT NULL CHECK (total_weight_g BETWEEN 0 AND 2000000000),
  delivery_state    varchar(20) NOT NULL CHECK (delivery_state IN ('Pending', 'Delivered')),
  created_at        timestamptz NOT NULL,
  last_attempt_at   timestamptz,
  attempts          integer     NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 100000),
  delivered_at      timestamptz,
  CONSTRAINT pick_list_delivered_ck CHECK ((delivery_state = 'Delivered') = (delivered_at IS NOT NULL))
);

CREATE INDEX pick_list_delivery_state_idx ON pick_list (delivery_state, id);

-- Backfill (C-16): every Accepted Order recorded before V2 gets one pending Pick List
INSERT INTO pick_list (customer_order_id, file_name, total_weight_g, delivery_state, created_at, attempts)
SELECT c.id,
       'PL-' || c.order_number || '.csv',
       (SELECT COALESCE(SUM(l.quantity * l.unit_weight_grams), 0) FROM order_line l WHERE l.customer_order_id = c.id),
       'Pending',
       now(),
       0
FROM customer_order c
JOIN order_receipt r ON r.id = c.order_receipt_id
WHERE r.order_state = 'Recorded'
  AND NOT EXISTS (SELECT 1 FROM pick_list p WHERE p.customer_order_id = c.id)
ORDER BY c.id;
