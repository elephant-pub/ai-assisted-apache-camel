-- Order Database schema for the Peakmart intake prototype (names and rules from docs/entity_model.md).
-- One DO block, so camel-sql runs it as a single statement; every statement is IF NOT EXISTS, so it is safe to repeat.
-- Not created (Not Doing): partner, pick_list, alert, alerted_order, order_event_resubmission.
DO $$
BEGIN
  CREATE TABLE IF NOT EXISTS order_receipt (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number    varchar(30)  NOT NULL,
    channel         varchar(20)  NOT NULL CHECK (channel IN ('Partner', 'Peakmart')),
    partner_id      bigint,
    event_id        varchar(100),
    content_hash    varchar(64)  NOT NULL,
    correlation_id  varchar(36)  NOT NULL UNIQUE,
    received_at     timestamptz  NOT NULL,
    order_state     varchar(20)  NOT NULL
                    CHECK (order_state IN ('Received', 'Rejected', 'Recorded', 'Sent to Warehouse')),
    checking_since  timestamptz,
    waiting_for     varchar(20)  CHECK (waiting_for IN ('Check', 'Recording')),
    waiting_order   text,
    CONSTRAINT order_receipt_channel_ids_ck CHECK (
      (channel = 'Partner' AND partner_id IS NOT NULL AND event_id IS NULL)
      OR (channel = 'Peakmart' AND event_id IS NOT NULL AND partner_id IS NULL)),
    CONSTRAINT order_receipt_checking_since_ck CHECK (
      checking_since IS NULL OR (channel = 'Partner' AND order_state = 'Received')),
    CONSTRAINT order_receipt_waiting_ck CHECK (
      (waiting_for IS NULL AND waiting_order IS NULL)
      OR (waiting_for IS NOT NULL AND waiting_order IS NOT NULL
          AND channel = 'Peakmart' AND order_state = 'Received'))
  );
  CREATE UNIQUE INDEX IF NOT EXISTS order_receipt_peakmart_order_number_uq
    ON order_receipt (order_number) WHERE channel = 'Peakmart';

  CREATE TABLE IF NOT EXISTS order_state_change (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_receipt_id bigint      NOT NULL REFERENCES order_receipt (id),
    order_state      varchar(20) NOT NULL
                     CHECK (order_state IN ('Received', 'Rejected', 'Recorded', 'Sent to Warehouse')),
    changed_at       timestamptz NOT NULL,
    CONSTRAINT order_state_change_uq UNIQUE (order_receipt_id, order_state)
  );

  CREATE TABLE IF NOT EXISTS rejection_reason (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_receipt_id bigint       NOT NULL REFERENCES order_receipt (id),
    order_check      varchar(40)  NOT NULL CHECK (order_check IN (
                       'Order Number Format', 'Order Number Range', 'Order Number Already Used', 'SKU', 'Quantity',
                       'Number of Order Lines', 'Shipping Address', 'Destination Country')),
    line_number      integer      CHECK (line_number BETWEEN 1 AND 30),
    reason_text      varchar(500) NOT NULL,
    position         integer      NOT NULL CHECK (position BETWEEN 1 AND 100),
    CONSTRAINT rejection_reason_position_uq UNIQUE (order_receipt_id, position)
  );

  CREATE TABLE IF NOT EXISTS notification (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_receipt_id  bigint       NOT NULL UNIQUE REFERENCES order_receipt (id),
    notification_type varchar(30)  NOT NULL
                      CHECK (notification_type IN ('Rejection Email', 'Order Desk Notification')),
    recipient_email   varchar(254) NOT NULL CHECK (recipient_email ~ '^[^@\s]+@[^@\s]+[.][^@\s]+$'),
    created_at        timestamptz  NOT NULL,
    sent_at           timestamptz,
    attempts          integer      NOT NULL CHECK (attempts BETWEEN 0 AND 1000)
  );

  CREATE TABLE IF NOT EXISTS customer_order (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_receipt_id bigint       NOT NULL UNIQUE REFERENCES order_receipt (id),
    order_number     varchar(30)  NOT NULL UNIQUE,
    ordered_at       timestamptz  NOT NULL,
    customer_email   varchar(254) CHECK (customer_email ~ '^[^@\s]+@[^@\s]+[.][^@\s]+$'),
    recipient_name   varchar(100) NOT NULL,
    street_line      varchar(200) NOT NULL,
    city             varchar(100) NOT NULL,
    state_region     varchar(50),
    postal_code      varchar(20)  NOT NULL,
    country          varchar(2)   NOT NULL CHECK (country IN ('US', 'CA')),
    recorded_at      timestamptz  NOT NULL
  );

  CREATE TABLE IF NOT EXISTS order_line (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_order_id bigint        NOT NULL REFERENCES customer_order (id),
    line_number       integer       NOT NULL CHECK (line_number BETWEEN 1 AND 30),
    sku               varchar(50)   NOT NULL,
    product_name      varchar(200)  NOT NULL,
    quantity          integer       NOT NULL CHECK (quantity BETWEEN 1 AND 20),
    unit_price        numeric(10,2) NOT NULL CHECK (unit_price BETWEEN 0 AND 99999999.99),
    unit_weight_grams integer       NOT NULL CHECK (unit_weight_grams BETWEEN 0 AND 1000000),
    CONSTRAINT order_line_number_uq UNIQUE (customer_order_id, line_number)
  );

  CREATE TABLE IF NOT EXISTS set_aside_order_event (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id           varchar(100) NOT NULL UNIQUE,
    order_number       varchar(30),
    event_content      text         NOT NULL,
    cannot_read_reason varchar(500) NOT NULL,
    arrived_at         timestamptz  NOT NULL,
    set_aside_state    varchar(20)  NOT NULL CHECK (set_aside_state IN ('Set Aside', 'Resubmitted'))
  );
END
$$
